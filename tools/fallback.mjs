// Generates src/fallback-flat.css: the last resort for browsers without color-mix() (Chrome and
// Edge before 111, Safari before 16.2, Firefox before 113), flat values of every public colour token,
// read in Chromium from the built dials.css (the Hi-Fi defaults, light scheme). Its header records a
// hash of src/colour.css, so `python3 build.py --check` can tell when it's stale.
//
//   node tools/fallback.mjs           write src/fallback-flat.css (then run python3 build.py)
//   node tools/fallback.mjs --check   exit 1 if src/fallback-flat.css is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { serve, launch, pageHelpers, ROOT } from '../checks/lib.mjs';

const check = process.argv.includes('--check');
const ref = JSON.parse(readFileSync(join(ROOT, 'docs/tokens.json'), 'utf8'));
// colour tokens only: never a dial, and not the ungrouped five, which the group classes set
const UNGROUPED = ['--solid', '--on-solid', '--soft', '--on-soft', '--line'];
const names = ref.tokens.filter(t => t.file === 'dials-colour.css' && !UNGROUPED.includes(t.name)).map(t => t.name);
const hash = createHash('sha256').update(readFileSync(join(ROOT, 'src/colour.css'))).digest('hex').slice(0, 16);

const server = await serve({ '/__fallback': () => `<!doctype html><html><head><link rel="stylesheet" href="/dials.css"></head>
<body style="color-scheme: light"><div id="box" style="color: rgb(1, 2, 3)"></div></body></html>` });
const browser = await launch('chromium');
const page = await browser.newPage();
await page.addInitScript(pageHelpers);
await page.goto(`${server.url}/__fallback`, { waitUntil: 'load' });
const values = await page.evaluate((names) => {
  document.documentElement.style.colorScheme = 'light';
  const box = document.getElementById('box'), cs = getComputedStyle(document.documentElement);
  const flat = (c) => { const [r, g, b, a] = __rgba(c); return a < 1 ? `rgb(${r} ${g} ${b} / ${Math.round(a * 100)}%)` : __hex([r, g, b]); };
  const colour = (v) => { const el = document.createElement('i'); el.style.color = `var(${v})`; box.appendChild(el); const s = getComputedStyle(el).color; el.remove(); return s === 'rgb(1, 2, 3)' ? null : flat(s); };
  const out = {}, skipped = [];
  for (const n of names) {
    const c = colour(n);
    if (c) { out[n] = c; continue; }
    skipped.push(n);
  }
  const angle = cs.getPropertyValue('--gradient-angle').trim();
  out['--gradient-solid'] = `linear-gradient(${angle}, ${colour('--gradient-from')}, ${colour('--gradient-to')})`;
  out['--gradient-soft'] = `linear-gradient(${angle}, ${colour('--gradient-soft-from')}, ${colour('--gradient-soft-to')})`;
  for (const s of ['s', 'm', 'l']) {   // keep the geometry, flatten the colour
    const geo = cs.getPropertyValue(`--shadow-${s}`).trim().match(/^((?:-?[\d.]+(?:px)?\s+){2,3})/);
    out[`--shadow-${s}`] = geo[1].trim() + ' ' + out['--shadow-color'];
  }
  out['--mix-hover'] = 'black 12%';
  out['--mix-active'] = 'black 22%';
  return { out, skipped };
}, names);
await browser.close(); await server.close();

const missing = values.skipped.filter(n => !(n in values.out));
if (missing.length) { console.error('fallback.mjs: no flat value for ' + missing.join(', ')); process.exit(2); }
const body = names.map(k => `    ${k}: ${values.out[k]};`).join('\n');
const css = `/* Generated by tools/fallback.mjs from dials.css (src/colour.css ${hash}): the Hi-Fi defaults in
   the light scheme. Don't edit. The last resort, for browsers without color-mix() (Chrome and Edge
   before 111, Safari before 16.2, Firefox before 113, all 2022 or older): they can't work anything
   out, so every colour token is flat and they get the house colours, light only. Colour dials have no
   effect there; type and space work as normal. */
@supports not (color: color-mix(in srgb, red, blue)) {
  :root, [data-dials], :host, .is-light, .is-dark {
    color-scheme: light;
${body}
  }
}
`;
const file = join(ROOT, 'src/fallback-flat.css');
if (check) {
  const now = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (now !== css) { console.log('stale: src/fallback-flat.css. Run: node tools/fallback.mjs && python3 build.py'); process.exit(1); }
  console.log(`fallback.mjs --check: src/fallback-flat.css is up to date (${names.length} tokens)`);
} else {
  writeFileSync(file, css);
  console.log(`wrote src/fallback-flat.css (${names.length} tokens). Now run: python3 build.py`);
}
