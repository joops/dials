// Generates src/fallback.css: flat values of every public colour token for browsers without
// relative colour, read in Chromium from the built dials.css (the Hi-Fi defaults, light scheme).
//
//   node tools/fallback.mjs           write src/fallback.css (then run python3 build.py)
//   node tools/fallback.mjs --check   exit 1 if src/fallback.css is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { serve, launch, pageHelpers, ROOT } from '../checks/lib.mjs';

const check = process.argv.includes('--check');
const ref = JSON.parse(readFileSync(join(ROOT, 'docs/tokens.json'), 'utf8'));
// colour dials too: a theme or component may read them directly
const names = [...ref.dials, ...ref.tokens].map(t => t.name).filter(n => !/^--(size|space|radius|font|border-width|screen|ratio|balance|fill-|dark-lift|tint-|text-contrast|white-text|paper-|ink-|gradient-angle)/.test(n));

const server = await serve({ '/__fallback': () => `<!doctype html><html><head><link rel="stylesheet" href="/dials.css"></head>
<body style="color-scheme: light"><div id="box" style="color: rgb(1, 2, 3)"></div></body></html>` });
const browser = await launch('chromium');
const page = await browser.newPage();
await page.addInitScript(pageHelpers);
await page.goto(`${server.url}/__fallback`, { waitUntil: 'load' });
const values = await page.evaluate((names) => {
  document.documentElement.style.colorScheme = 'light';
  const box = document.getElementById('box'), cs = getComputedStyle(document.documentElement);
  const flat = (c) => { const [r, g, b, a] = __rgba(c); return a < 1 ? `rgb(${r} ${g} ${b} / ${Math.round(a * 100)}%)` : __hex([r, g, b]); };
  const colour = (v) => { const el = document.createElement('i'); el.style.color = `var(${v})`; box.appendChild(el); const s = getComputedStyle(el).color; el.remove(); return s === 'rgb(1, 2, 3)' ? null : flat(s); };
  const out = {}, skipped = [];
  for (const n of names) {
    const c = colour(n);
    if (c) { out[n] = c; continue; }
    skipped.push(n);
  }
  const angle = cs.getPropertyValue('--gradient-angle').trim();
  out['--gradient-solid'] = `linear-gradient(${angle}, ${colour('--gradient-from')}, ${colour('--gradient-to')})`;
  out['--gradient-soft'] = `linear-gradient(${angle}, ${colour('--gradient-soft-from')}, ${colour('--gradient-soft-to')})`;
  for (const s of ['s', 'm', 'l']) {   // keep the geometry, flatten the colour
    const geo = cs.getPropertyValue(`--shadow-${s}`).trim().match(/^((?:-?[\d.]+(?:px)?\s+){2,3})/);
    out[`--shadow-${s}`] = geo[1].trim() + ' ' + out['--shadow-color'];
  }
  out['--mix-hover'] = 'black 12%';
  out['--mix-active'] = 'black 22%';
  return { out, skipped };
}, names);
await browser.close(); await server.close();

const missing = values.skipped.filter(n => !(n in values.out));
if (missing.length) { console.error('fallback.mjs: no flat value for ' + missing.join(', ')); process.exit(2); }
const body = Object.entries(values.out).map(([k, v]) => `    ${k}: ${v};`).join('\n');
const css = `/* Generated by tools/fallback.mjs from dials.css: the Hi-Fi defaults in the light scheme. Don't edit.
   Browsers without relative colour (Chrome and Edge before 119, Safari before 18, Firefox before 128)
   can't work out the derived tokens, so they get these flat values instead: the house theme, light
   only. Dials, themes, [data-dials] scopes and .is-dark bands have no effect there; everything else,
   including type and space, works as normal. */
@supports not (color: oklch(from red l c h)) {
  :root:root, [data-dials][data-dials] {
    color-scheme: light;
${body}
  }
  .is-dark.is-dark { color-scheme: light; }
}
`;
const file = join(ROOT, 'src/fallback.css');
if (check) {
  const now = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (now !== css) { console.log('stale: src/fallback.css. Run: node tools/fallback.mjs && python3 build.py'); process.exit(1); }
  console.log(`fallback.mjs --check: src/fallback.css is up to date (${Object.keys(values.out).length} tokens)`);
} else {
  writeFileSync(file, css);
  console.log(`wrote src/fallback.css (${Object.keys(values.out).length} tokens). Now run: python3 build.py`);
}
